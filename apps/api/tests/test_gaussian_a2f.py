def test_resampler_is_invariant_to_odd_chunk_boundaries_and_preserves_duration():
    audio = np.random.default_rng(24).integers(-28000, 28000, size=24017, dtype=np.int16).astype("<i2").tobytes()
    single = PCM16Resampler().push(audio, final=True)
    streaming = PCM16Resampler()
    chunks = [streaming.push(audio[i:i + 127]) for i in range(0, len(audio), 127)]
    chunks.append(streaming.push(b"", final=True))
    assert b"".join(chunks) == single
    assert len(single) // 2 == math.ceil(24017 * 16000 / 24000)


def test_resampler_filters_above_output_nyquist_and_retains_speech_band():
    def rms(frequency):
        data = (np.sin(np.arange(24000) * 2 * np.pi * frequency / 24000) * 20000).astype("<i2").tobytes()
        output = np.frombuffer(PCM16Resampler().push(data, final=True), "<i2").astype(float)[100:-100]
        return np.sqrt(np.mean(output ** 2))
    assert rms(1000) > 13000
    assert rms(10000) < 400


def test_resampler_preserves_16k_bytes_and_rejects_truncated_pcm():
    converter = PCM16Resampler(16000)
    assert converter.push(b"\x01") == b""
    assert converter.push(b"\x02\x03\x04", final=True) == b"\x01\x02\x03\x04"
    with pytest.raises(ValueError, match="incomplete"):
        PCM16Resampler().push(b"\x01", final=True)


def test_name_mapping_does_not_depend_on_nvidia_channel_order():
    mapped = canonical_weights({"JawOpen": 0.3, "Eye_Blink_Left": 1.2, "HeadYaw": 10., "MouthSmileRight": float("nan")})
    assert len(mapped) == len(ARKIT_NAMES) == 52
    assert mapped["jawOpen"] == .3
    assert mapped["eyeBlinkLeft"] == 1.
    assert mapped["mouthSmileRight"] == 0.
    assert "HeadYaw" not in mapped


def test_header_wire_numbers_match_official_ace_contract():
    # Independent wire fixture: AudioStream(1)->Header(1)->AudioHeader;
    # field2=mono, field3=16000, field4=16. Not generated by our descriptor.
    header = _protocol()["AudioStream"].FromString(bytes.fromhex("0a090a07100118807d2010"))
    assert header.audio_stream_header.audio_header.samples_per_second == 16000
    assert header.audio_stream_header.audio_header.channel_count == 1
    assert header.audio_stream_header.audio_header.bits_per_sample == 16


def test_grpc_stream_sends_audio_before_end_and_decodes_named_frames():
    async def run():
        proto = _protocol()
        received = []

        async def handler(requests, context):
            async for request in requests:
                received.append(request)
                if request.HasField("audio_stream_header"):
                    response = proto["AnimationDataStream"]()
                    response.animation_data_stream_header.skel_animation_header.blend_shapes.extend(["JawOpen", "EyeBlinkLeft", "HeadYaw"])
                    yield response
                if request.HasField("audio_with_emotion"):
                    response = proto["AnimationDataStream"]()
                    frame = response.animation_data.skel_animation.blend_shape_weights.add()
                    frame.time_code = (len(received) - 2) / 30.
                    frame.values.extend([.4, .2, 5.])
                    yield response
                if request.HasField("end_of_audio"):
                    response = proto["AnimationDataStream"]()
                    response.status.code = 0
                    yield response

        server = grpc.aio.server()
        server.add_generic_rpc_handlers((grpc.method_handlers_generic_handler(
            "nvidia_ace.services.a2f_controller.v1.A2FControllerService",
            {"ProcessAudioStream": grpc.stream_stream_rpc_method_handler(
                handler, request_deserializer=proto["AudioStream"].FromString,
                response_serializer=lambda item: item.SerializeToString())}),))
        port = server.add_insecure_port("127.0.0.1:0")
        await server.start()
        try:
            async def pcm():
                yield struct.pack("<2400h", *([200] * 2400))
            events = []
            result = [frame async for frame in A2FClient(f"127.0.0.1:{port}", trace=lambda e, p: events.append(e)).stream(pcm())]
            assert received[0].audio_stream_header.audio_header.samples_per_second == 16000
            assert received[0].audio_stream_header.emotion_post_processing_params.HasField("emotion_strength")
            assert received[0].audio_stream_header.emotion_post_processing_params.emotion_strength == 0.
            assert received[-1].HasField("end_of_audio")
            assert sum(len(item.audio_with_emotion.audio_buffer) for item in received) == 3200
            assert result[0].coefficients["jawOpen"] == pytest.approx(.4)
            assert result[0].coefficients["eyeBlinkLeft"] == pytest.approx(.2)
            assert len(result[0].coefficients) == 52
            assert events[-1] == "a2f.complete"
        finally:
            await server.stop(0)
    asyncio.run(run())


def test_unreachable_a2f_reports_failure_without_synthetic_frames():
    async def run():
        async def pcm():
            yield bytes(4800)
        with pytest.raises(A2FError, match="timed out"):
            async for _ in A2FClient("127.0.0.1:1", connect_timeout_seconds=.05).stream(pcm()):
                pytest.fail("Unavailable A2F must not create fabricated animation")
    asyncio.run(run())


@pytest.mark.skipif(not os.environ.get("GAUSSIAN_A2F_LIVE_TEST"), reason="Explicit local NVIDIA service integration test")
def test_live_nvidia_service_produces_speech_motion():
    async def run():
        fixture = Path(__file__).parents[1] / "app" / "assets" / "test-reference.wav"
        with wave.open(str(fixture), "rb") as audio:
            assert audio.getnchannels() == 1 and audio.getsampwidth() == 2
            sample_rate = audio.getframerate()
            raw = audio.readframes(sample_rate * 2)
        # Exercise the Realtime PCM24k -> A2F16k path with actual speech.
        source = np.frombuffer(raw, "<i2").astype(float)
        raw = np.interp(np.arange(round(len(source) * 24000 / sample_rate)) * sample_rate / 24000,
                        np.arange(len(source)), source).astype("<i2").tobytes()
        sample_rate = 24000
        async def pcm():
            for offset in range(0, len(raw), 3200):
                yield raw[offset:offset + 3200]
                await asyncio.sleep(.02)
        client = A2FClient(os.environ.get("GAUSSIAN_A2F_ENDPOINT", "localhost:52000"))
        assert (await client.health())["ready"]
        frames = [frame async for frame in client.stream(pcm(), input_sample_rate=sample_rate)]
        assert len(frames) >= 50
        assert frames[-1].time_seconds >= 1.9
        assert max(frame.weights["jawOpen"] for frame in frames) > .1
        assert all(len(frame.weights) == 52 for frame in frames)
        assert all(b.time_seconds > a.time_seconds for a, b in zip(frames, frames[1:]))
    asyncio.run(run())
